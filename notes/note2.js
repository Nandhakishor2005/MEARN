// javascript Arithmetic operators

let a=10;
let b=20;

console.log(a+b);
console.log(a-b);
console.log(a*b);
console.log(a/b);
console.log(a%b);
console.log(a++);
console.log(a--);
console.log(b++);
console.log(b--);
console.log(a**b);

// javascript Relational operators

let x=10;
console.log(x==5);
console.log(x===5);
console.log(x!=5);
console.log(x!==5);
console.log(x>5);
console.log(x<5);
console.log(x>=5);
console.log(x<=5);


// javascript Logical operators

console.log(5>3 && 10>5);
console.log(5>10 || 10>5);
console.log(!5>3);



